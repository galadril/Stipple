// The default 5x7 proportional face.
//
// These letterforms are authored for NOTRIX rather than copied from an existing
// font file, which keeps THIRD_PARTY_NOTICES.md accurate and avoids inheriting
// anyone else's licence for a table that ships inside the firmware.
//
// Authoring rules (see Font.h):
//   - each row is five bits, MSB = leftmost column, so the literals read as they
//     render;
//   - glyphs narrower than the cell are LEFT-aligned, e.g. '!' is 0b10000;
//   - `width` is the proportional advance in columns, before letter spacing.
//
// Vertical metrics: capitals and digits fill rows 0-6. Lowercase x-height sits
// on rows 2-6. The five descender letters (g j p q y) start at row 1 so their
// tail reaches row 6 — at seven rows tall there is no room below the baseline,
// so the descender is implied rather than drawn true.
//
// COVERAGE CAVEAT: accented *lowercase* works because an x-height of five rows
// leaves two rows for the accent. Accented *capitals* do not fit — a capital
// needs all seven rows, leaving nowhere for the mark — so U+00C4 and friends are
// deliberately absent and fall back to the tofu box. Serving them properly needs
// the 8-row tier, which is a later font pack.

