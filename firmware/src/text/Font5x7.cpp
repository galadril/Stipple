const Glyph* BitmapFont::find(char32_t codepoint) const noexcept {
    if (glyphCount_ == 0 || codepoint > 0xFFFFu) {
        return nullptr;
    }

    const std::uint16_t needle = static_cast<std::uint16_t>(codepoint);
    std::size_t low = 0;
    std::size_t high = glyphCount_;

    while (low < high) {
        const std::size_t mid = low + (high - low) / 2;
        const std::uint16_t candidate = glyphs_[mid].codepoint;
        if (candidate == needle) {
            return &glyphs_[mid];
        }
        if (candidate < needle) {
            low = mid + 1;
        } else {
            high = mid;
        }
    }
    return nullptr;
}

const Glyph& BitmapFont::glyphFor(char32_t codepoint) const noexcept {
    if (const Glyph* exact = find(codepoint)) {
        return *exact;
    }
    if (const Glyph* tofu = find(0xFFFDu)) {
        return *tofu;
    }
    return glyphs_[0];
}

const BitmapFont& font5x7() noexcept {
    return kFont5x7;
}

